/** Data-driven cases get their own ID (TC08.1, TC08.2 ...): one catalogue entry per data row. */
function variant(from: string, to: string, data: string, expected?: string): void {
  const base = CATALOG[from];
  if (!base) throw new Error(`catalogue: unknown base case ${from}`);
  CATALOG[to] = { ...base, data, expected: expected ?? base.expected };
}
